/**
 * Object keys always start with the agency id, so one tenant's objects sit in a
 * distinguishable prefix and a bucket policy or lifecycle rule can be written
 * per agency later without a migration.
 */
export function buildKey(parts: {
  agencyId: string;
  entity: string;
  entityId: string;
  filename: string;
}): string {
  const extension = parts.filename.includes(".")
    ? parts.filename.split(".").pop()!.toLowerCase().replace(/[^a-z0-9]/g, "")
    : "bin";
  return `agency/${parts.agencyId}/${parts.entity}/${parts.entityId}/${crypto.randomUUID()}.${extension}`;
}

/**
 * Reject anything that could escape the storage root.
 *
 * Keys are generated by `buildKey`, but they round-trip through the database and
 * a URL before they are used to open a file, so they are validated again here.
 */
export function isSafeKey(key: string): boolean {
  if (!key || key.length > 512) return false;
  if (key.startsWith("/") || key.startsWith("\\")) return false;
  if (key.includes("..")) return false;
  if (key.includes("\0")) return false;
  return /^[A-Za-z0-9/._-]+$/.test(key);
}
